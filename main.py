# 🧠  AUTO-CALIBRATE (RAM 90%, CPU 80%)
# ============================================================================

def auto_calibrate() -> Tuple[int, int, int, bool]:
    """
    محاسبه خودکار هم‌روندی، اندازه چانک، timeout و حالت Safe Mode
    استفاده حداکثری از منابع: RAM تا 90%، CPU تا 80%
    بازگشت: (concurrency, chunk_size, inertia_timeout_ms, safe_mode)
    """
    cpu_cores = os.cpu_count() or 4
    mem_total_gb = psutil.virtual_memory().total / (1024 ** 3) if HAS_PSUTIL else 8
    mem_available_gb = psutil.virtual_memory().available / (1024 ** 3) if HAS_PSUTIL else 4

    # تشخیص Safe Mode: حافظه کل کمتر از 2 گیگ یا هسته‌ها کمتر از 4
    safe_mode = (mem_total_gb < 2 or cpu_cores < 4)

    if safe_mode:
        return 50, 100, 60000, True  # 60 ثانیه timeout

    # محاسبه هم‌روندی: هر هسته 40 اتصال + هر گیگ رم 15 اتصال، با سقف 500
    concurrency = max(30, min(int(cpu_cores * 40 + mem_total_gb * 15), 500))
    
    # اندازه چانک: متناسب با هم‌روندی، حداقل 100 و حداکثر 3000
    chunk_size = max(100, min(int(concurrency * 2.0), 3000))
    
    # زمان timeout برای inertia (میلی‌ثانیه): حداقل 60 ثانیه، به ازای هر 100 آی‌پی 5 ثانیه اضافه
    timeout_sec = max(60, int(chunk_size / 100 * 5) + 30)
    inertia_timeout_ms = timeout_sec * 1000  # تبدیل به میلی‌ثانیه
    
    return concurrency, chunk_size, inertia_timeout_ms, safe_mode


