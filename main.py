class ResourceMonitor:
    def __init__(self):
        self.cpu_percent = 0
        self.memory_percent = 0
        self.memory_available_gb = 4
        self.net_speed = 0
        self.net_packets_dropped = 0
        self._running = True
        self._thread = None
        self._last_net = None
        self._last_time = time.time()
        self._last_net_dropped = 0
        
        if HAS_PSUTIL:
            self._thread = threading.Thread(target=self._monitor, daemon=True)
            self._thread.start()
    
    def _monitor(self):
        while self._running:
            if HAS_PSUTIL:
                self.cpu_percent = psutil.cpu_percent(interval=0.5)
                mem = psutil.virtual_memory()
                self.memory_percent = mem.percent
                self.memory_available_gb = mem.available / (1024 ** 3)
                net = psutil.net_io_counters()
                now = time.time()
                if self._last_net:
                    dt = now - self._last_time
                    if dt > 0:
                        self.net_speed = ((net.bytes_sent + net.bytes_recv) - 
                                         (self._last_net.bytes_sent + self._last_net.bytes_recv)) / dt / 1024 / 1024
                        self.net_packets_dropped = (net.dropin + net.dropout) - self._last_net_dropped
                self._last_net = net
                self._last_net_dropped = net.dropin + net.dropout
                self._last_time = now
            time.sleep(0.5)
    
    def get_status(self) -> Dict[str, Any]:
        return {
            'cpu': self.cpu_percent,
            'memory': self.memory_percent,
            'memory_available_gb': self.memory_available_gb,
            'network_speed': self.net_speed,
            'packets_dropped': self.net_packets_dropped,
        }
    
    def stop(self):
        self._running = False


