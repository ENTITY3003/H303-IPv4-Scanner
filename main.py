class SubnetChunkGenerator:
    def __init__(self, subnets: List[str], chunk_size: int):
        self.subnets = subnets
        self.chunk_size = chunk_size
        self.subnet_info = []
        self.current_subnet_idx = 0
        self.total_ips = 0
        self._prepare_subnets()
        random.shuffle(self.subnet_info)
    
    def _prepare_subnets(self):
        for net_str in self.subnets:
            try:
                net = ipaddress.ip_network(net_str, strict=False)
                total = net.num_addresses - 2
                if total <= 0:
                    continue
                self.subnet_info.append({
                    'network': net,
                    'total': total,
                    'chunk_index': 0
                })
                self.total_ips += total
            except Exception:
                continue
    
    def _get_chunk_ips(self, info: Dict) -> List[str]:
        net = info['network']
        chunk_idx = info['chunk_index']
        start = chunk_idx * self.chunk_size
        end = min(start + self.chunk_size, info['total'])
        if start >= info['total']:
            return []
        ips = []
        for offset in range(start, end):
            ip = net.network_address + offset + 1
            ips.append(str(ip))
        return ips
    
    def __iter__(self):
        return self
    
    def __next__(self) -> List[str]:
        active = [i for i, info in enumerate(self.subnet_info) 
                  if info['chunk_index'] * self.chunk_size < info['total']]
        if not active:
            raise StopIteration
        
        start_idx = self.current_subnet_idx
        for i in range(len(active)):
            idx = (start_idx + i) % len(self.subnet_info)
            info = self.subnet_info[idx]
            if info['chunk_index'] * self.chunk_size < info['total']:
                chunk_ips = self._get_chunk_ips(info)
                info['chunk_index'] += 1
                self.current_subnet_idx = (idx + 1) % len(self.subnet_info)
                return chunk_ips
        
        raise StopIteration
    
    def total_ips_count(self) -> int:
        return self.total_ips
    
    def progress(self) -> Dict[str, Any]:
        total_used = 0
        total_all = 0
        for info in self.subnet_info:
            total_all += info['total']
            used = min(info['chunk_index'] * self.chunk_size, info['total'])
            total_used += used
        return {
            'total': total_all,
            'used': total_used,
            'remaining': total_all - total_used,
            'percent': (total_used / total_all * 100) if total_all > 0 else 0,
        }


